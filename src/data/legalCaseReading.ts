export const getCaseReading = (item: LegalCaseCard): CaseReading & { background: string[] } => {
  const reading = caseReadingByKey[`${item.city}|${item.id}`];
  return {
    title: reading?.title || (/^[A-Z]{2}-S\d+$/.test(item.id) ? "劳动争议案例" : item.id),
    issue: reading?.issue,
    // 只按完整句号分段，保留年月、金额小数和原始案情的全部信息。
    background: reading?.background || (item.summary.match(/[^。]+(?:。|$)/g) || [item.summary]),
    reasoning: reading?.reasoning || item.reasoning,
    outcome: reading?.outcome || item.outcome,
    sourceLabel: reading?.sourceLabel || item.sourceLabel,
  };
};
